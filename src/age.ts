const LAST = ID_DATES[ID_DATES.length-1]!;
const FIRST = ID_DATES[0]!;

export function estimateRegistrationMs(userId: number): number | null {
  if (userId <= FIRST[0]) return FIRST[1];
  if (userId >= LAST[0]) return null;
  let lo = 0, hi = ID_DATES.length - 1;
  while (hi - lo > 1) {
    const mid = (lo + hi) >> 1;
    if (ID_DATES[mid]![0] <= BigInt(userId)) lo = mid; else hi = mid;
  }
  const a = ID_DATES[lo]!, b = ID_DATES[hi]!;
  const t = Number(BigInt(userId) - a[0]) / Number(b[0] - a[0]);
  return Math.round(a[1] + t * (b[1] - a[1]));
}

export function estimateAccountAgeDays(userId: number): number | null {
  const est = estimateRegistrationMs(userId);
  if (est == null) return null;
  return Math.max(0, (Date.now() - est) / 86400000);
}

export function isNewerThan(userId: number, minAgeDays: number): boolean | null {
  const age = estimateAccountAgeDays(userId);
  if (age == null) return null;
  return age < minAgeDays;
}
